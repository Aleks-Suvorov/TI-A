def emit_pine_constants(model: dict[str, Any] | str | Path, *pine_paths: str | Path) -> list[Path]:
    """Rewrite the ``BEGIN/END FROZEN MODEL`` region of each ``.pine`` file.

    The region is replaced wholesale, so the generated block is never merged
    with hand edits -- which is the point: a Pine script whose constants have
    been touched by hand no longer corresponds to any manifest hash.
    """
    if isinstance(model, (str, Path)):
        model = json.loads(Path(model).read_text(encoding="utf-8"))
    region = _pine_region(model)  # type: ignore[arg-type]
    pattern = re.compile(
        re.escape(PINE_BEGIN_MARKER) + r".*?" + re.escape(PINE_END_MARKER),
        re.DOTALL,
    )
    written: list[Path] = []
    for pp in pine_paths:
        p = Path(pp)
        text = p.read_text(encoding="utf-8")
        if not pattern.search(text):
            raise ValueError(f"{p} has no BEGIN/END FROZEN MODEL region")
        p.write_text(pattern.sub(lambda _m: region, text, count=1), encoding="utf-8")
        written.append(p)
    return written


