def export_frozen_model(
    system: Any,
    path: str | Path,
    *,
    dev_universe: dict[str, Any] | None = None,
    training: dict[str, Any] | None = None,
    tempering: tuple[float, float, int] | None = None,
    engine_correlation: np.ndarray | None = None,
    correlation_source: str = "",
) -> dict[str, Any]:
    """Write the frozen manifest for ``system`` to ``path`` and return it.

    ``system`` is a trained :class:`tia.pipeline.TIA`: its ``edge_book`` holds
    observed outcomes, its ``calibrator`` holds a fitted isotonic map (or does
    not, in which case the port falls back to the parametric link), and its
    ``calop`` has seen enough bars for the engine correlation estimate to be the
    measured one rather than the 0.35-everywhere cold-start prior.

    ``tempering`` optionally supplies ``(median, sd, n)`` for the regime
    tempering exponent measured over the training run. Without it the exporter
    falls back to the engine's last value, which is a sample of one.
    """
    cfg: Config = system.cfg
    cal = getattr(system.calibrator, "_iso", None) or IsotonicCalibrator()
    health = {}
    try:
        health = system.calibrator.health()
    except Exception:  # pragma: no cover - health is best-effort metadata
        health = {}

    if tempering is None:
        t_med = float(getattr(system.regime_engine.state, "temper", 1.0))
        tempering = (t_med, 0.0, 1)
    t_med, t_sd, t_n = tempering

    model: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat(),
        "generator": "tia.export.export_frozen_model",
        "tia_version": cfg.version,
        "config_manifest_hash": cfg.manifest_hash(),
        "is_placeholder": False,
        "fitted_dof": cfg.fitted_dof(),
        "online_dof": cfg.online_dof(),
        "dev_universe": dev_universe or {},
        "training": training or {},
        "features": _feature_block(cfg),
        "regime": _regime_block(cfg, t_med, t_sd, t_n),
        "engines": _engine_block(system, cfg, engine_correlation, correlation_source),
        "fusion": _calibration_block(cal, cfg, int(getattr(system.calibrator, "n_samples", 0)), health),
        "edge_book": _edge_block(system.edge_book, cfg),
        "barriers": {
            "stop_sigma": _r(cfg.stop_sigma),
            "target_sigma": _r(cfg.target_sigma),
            "max_holding_bars": int(cfg.max_holding_bars),
            "min_holding_bars": int(cfg.min_holding_bars),
            "execution_lag_bars": int(cfg.execution_lag_bars),
        },
        "costs": {
            "impact_eta": _r(cfg.cost_impact_eta),
            "slippage_range_frac": _r(cfg.cost_slippage_range_frac),
            "fee_bps": _r(cfg.cost_fee_bps),
            "default_participation": _r(cfg.default_participation),
            "max_half_spread_sigma": _r(cfg.cost_max_half_spread_sigma),
            "spread_fallback_rel": 5e-4,
            "formula": "round_trip = 2 * (k*(S/2)/sigma + k*eta*sqrt(q) + k*phi*min(range/sigma,5) + fee/sigma), k = 1 + 1.5*p_stress",
        },
        "gate": {
            "ev_lcb_min_sigma": _r(cfg.ev_lcb_min_sigma),
            "p_min": _r(cfg.p_min),
            "p_exit": _r(cfg.p_exit),
            "ebe_min": _r(cfg.ebe_min),
            "regime_hazard_max": _r(cfg.regime_hazard_max),
            "max_trades_per_100_bars": _r(cfg.max_trades_per_100_bars),
            "allow_shorts": bool(cfg.allow_shorts),
        },
        "risk": {
            "kelly_fraction": _r(cfg.kelly_fraction),
            "risk_per_trade": _r(cfg.risk_per_trade),
            "max_risk_per_trade": _r(cfg.max_risk_per_trade),
            "dd_throttle_start": _r(cfg.dd_throttle_start),
            "dd_throttle_stop": _r(cfg.dd_throttle_stop),
            "dd_throttle_floor": _r(cfg.dd_throttle_floor),
            "dd_kill": _r(cfg.dd_kill),
        },
        "provenance": {
            p.value: {k: (list(v) if isinstance(v, tuple) else v) for k, v in cfg.by_provenance(p).items()}
            for p in Provenance
        },
        "pine": {
            "target_files": ["pine/TIA.pine", "pine/TIA_strategy.pine"],
            "begin_marker": PINE_BEGIN_MARKER,
            "end_marker": PINE_END_MARKER,
            "representation": (
                "Vectors and matrices become comma-separated string literals, "
                "row-major, split once on the first bar. Pine cannot read files "
                "or parse JSON at runtime."
            ),
        },
    }

    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(model, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    return model


