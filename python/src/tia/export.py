#: Rounding used for every exported float. Twelve significant digits is far more
#: than the estimation error of anything here and keeps the JSON diffable.
_SIG = 12


def _r(x: float) -> float | None:
    """Round a scalar for export. Missing becomes JSON ``null``, not a number.

    NaN previously mapped to ``-1e15``, because ``nan > 0`` is False. That is the
    worst possible encoding for a *missing* value: it is finite, plausible, and a
    consumer has no way to tell it apart from a real measurement. A calibration
    Brier score of -1e15 was reaching the exported manifest.

    True infinities keep a magnitude sentinel because they carry a direction and
    a meaning (an untradeable cost, for instance), and that meaning is worth
    preserving.
    """
    v = float(x)
    if v != v:
        return None
    if not math.isfinite(v):
        return 1e15 if v > 0 else -1e15
    return float(f"%.{_SIG}g" % v)


def _rv(xs: Iterable[float]) -> list[float]:
    """Round a vector. Vectors are consumed numerically by the port, so a
    non-finite entry is a defect rather than a value and is raised loudly."""
    out: list[float] = []
    for i, x in enumerate(xs):
        v = float(x)
        if not math.isfinite(v):
            raise ValueError(
                f"non-finite value {v!r} at index {i} of an exported vector; "
                "the port consumes these numerically and cannot represent it"
            )
        out.append(float(f"%.{_SIG}g" % v))
    return out


def _rm(m: Sequence[Sequence[float]]) -> list[list[float]]:
    return [[_r(x) for x in row] for row in m]


