def _pine_num(x: float | None) -> str:
    """Render one number for Pine. Missing becomes ``na``, which Pine understands
    and propagates correctly; a magnitude sentinel would be silently arithmetic."""
    if x is None:
        return "na"
    v = float(x)
    if v != v:
        return "na"
    if not math.isfinite(v):
        v = 1e15 if v > 0 else -1e15
    return f"{v:.10g}"


def _pine_csv(values: Sequence[float]) -> str:
    return ",".join(_pine_num(v) for v in values)


def _pine_csv_matrix(m: Sequence[Sequence[float]]) -> str:
    return ",".join(_pine_num(v) for row in m for v in row)


def _pine_region(model: dict[str, Any]) -> str:
    """Render the generated constant region. Row-major throughout."""
    reg = model["regime"]
    eng = model["engines"]
    fus = model["fusion"]
    eb = model["edge_book"]
    ft = model["features"]
    ba = model["barriers"]
    co = model["costs"]
    ga = model["gate"]
    ri = model["risk"]
    cells = eb["cells"]

    L: list[str] = [PINE_BEGIN_MARKER]
