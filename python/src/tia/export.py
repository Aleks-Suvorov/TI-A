def _log_beta_norm(a: float, b: float) -> float:
    """``ln B(a, b)`` -- the term :func:`tia.engines.regime.beta_logpdf` subtracts.

    Exported per cell because Pine has no log-gamma function and the shapes are
    frozen, so the whole normalising constant is a compile-time number there.
    """
    return math.lgamma(a) + math.lgamma(b) - math.lgamma(a + b)


def _regime_block(cfg: Config, temper: float, temper_sd: float, temper_n: int) -> dict[str, Any]:
    """The §5.2 measurement design, expanded into shapes Pine can use directly."""
    c = cfg.regime_beta_concentration
    a = np.ones((4, len(FEATURE_ORDER)))
    b = np.ones((4, len(FEATURE_ORDER)))
    m = np.full((4, len(FEATURE_ORDER)), 0.5)
    claims = np.zeros((4, len(FEATURE_ORDER)), dtype=int)
    for reg, row in DESIGN.items():
        for j, mv in enumerate(row):
            if mv is None:
                # Beta(1, 1) is exactly uniform: "this regime makes no claim
                # about this feature" contributes a likelihood factor of one and
                # lives inside the same parametric family. Theory §5.2.
                a[int(reg), j] = 1.0
                b[int(reg), j] = 1.0
                m[int(reg), j] = 0.5
                claims[int(reg), j] = 0
            else:
                a[int(reg), j] = max(mv * c, 1e-3)
                b[int(reg), j] = max((1.0 - mv) * c, 1e-3)
                m[int(reg), j] = mv
                claims[int(reg), j] = 1
    lognorm = np.array(
        [[_log_beta_norm(float(a[k, j]), float(b[k, j])) for j in range(a.shape[1])] for k in range(4)]
    )
    s = float(min(max(cfg.regime_stickiness, 0.5), 0.9999))
    return {
        "n_regimes": 4,
        "names": list(REGIME_NAMES),
        "feature_order": list(FEATURE_ORDER),
        "beta_concentration": _r(c),
        "design_m": _rm(m.tolist()),
        "design_makes_claim": claims.tolist(),
        "design_a": _rm(a.tolist()),
        "design_b": _rm(b.tolist()),
        "design_log_beta_norm": _rm(lognorm.tolist()),
        "stickiness": _r(s),
        "log_stay": _r(math.log(s)),
        "log_switch": _r(math.log((1.0 - s) / 3.0)),
        "tempering_exponent": _r(temper),
        "tempering_exponent_sd": _r(temper_sd),
        "tempering_exponent_samples": int(temper_n),
        "tempering_note": (
            "eta = EBE_f / J of THEORY 5.3, frozen. Python re-estimates it every "
            "bar from a rolling 8x8 feature correlation; the port takes the "
            "training-run median. tempering_exponent_sd bounds the resulting "
            "posterior error -- see docs/11-PINE-PLAN.md."
        ),
        "min_usable_features": 4,
        "feature_eps": 1e-6,
        "hazard_halflife_bars": _r(cfg.regime_shift_hazard_halflife),
        "hazard_max": _r(cfg.regime_hazard_max),
    }


def _engine_block(
    system: Any, cfg: Config, correlation: np.ndarray | None = None, source: str = ""
) -> dict[str, Any]:
    """Engine correlation structure, restricted to the engines the port runs."""
    names = list(getattr(system.calop, "names", PINE_ENGINE_ORDER))
    missing = [n for n in PINE_ENGINE_ORDER if n not in names]
    if missing:
        raise ValueError(f"trained system has no engine named {missing}")

    if correlation is not None:
        # A correlation estimated over exactly the ported engines. Preferred,
        # because CALOP.observe only feeds its estimator on bars where *every*
        # engine is valid -- and `crossasset` and `positioning` never are
        # without exogenous data, so the system's own estimate never leaves its
        # 0.35-everywhere cold-start prior. Exporting that prior as if it were
        # measured would be a lie of exactly the kind §6.4 warns about.
        c = np.asarray(correlation, dtype=np.float64)
        src = source or "measured over the ported engines during the export replay"
    else:
        idx = [names.index(n) for n in PINE_ENGINE_ORDER]
        # A principal sub-matrix of a ridge-regularised correlation matrix is
        # still positive definite, so restricting to the ported engines is safe.
        c = np.asarray(system.calop.correlation(), dtype=np.float64)[np.ix_(idx, idx)]
        src = source or "principal sub-matrix of CALOP.correlation()"
    cinv = np.linalg.inv(c)
    m = c.shape[0]
    ones = np.ones(m)
    off = c[~np.eye(m, dtype=bool)]
    return {
        "order": list(PINE_ENGINE_ORDER),
        "count": m,
        "correlation_source": src,
        "excluded": ["crossasset", "positioning"],
        "excluded_reason": (
            "crossasset requires ExogenousSnapshot peers/implied vol; positioning "
            "is enable_positioning_engine=False by default (config.py)."
        ),
        "correlation": _rm(c.tolist()),
        "precision": _rm(cinv.tolist()),
        "fusion_shrink": _r(cfg.fusion_shrink),
        "ebe_at_unit_reliability": _r(float(ones @ cinv @ ones)),
        "mean_abs_offdiag": _r(float(np.mean(np.abs(off))) if off.size else 0.0),
        "max_abs_offdiag": _r(float(np.max(np.abs(off))) if off.size else 0.0),
        "condition_number": _r(float(np.linalg.cond(c))),
        "warmup": {
            e.name: int(getattr(e, "warmup", 0))
            for e in system.engines
            if e.name in PINE_ENGINE_ORDER
        },
    }


def _calibration_block(cal: IsotonicCalibrator, cfg: Config, n_outcomes: int, health: dict[str, float]) -> dict[str, Any]:
    knots = cal.knots()
    xs = [k[0] for k in knots]
    ys = [k[1] for k in knots]
    return {
        "temperature": _r(cfg.fusion_temperature),
        "bias": _r(cfg.fusion_bias),
        "evidence_sd": _r(cfg.fusion_evidence_sd),
        "score_clamp": 0.999,
        "align_eps": 0.05,
        "credible_z": _r(1.6448536269514722),
        "isotonic_enabled": bool(cal.n_fit > 0),
        "isotonic_n_fit": int(cal.n_fit),
        "knots_x": _rv(xs),
        "knots_y": _rv(ys),
        "n_knots": len(xs),
        "min_samples": int(cfg.calibration_min_samples),
        "n_outcomes": int(n_outcomes),
        "brier": _r(health.get("brier", float("nan"))) if health else None,
        "ece": _r(health.get("ece", float("nan"))) if health else None,
        "interpolation": "linear between knots, clamped at the ends (numpy.interp semantics)",
    }


def _edge_block(book: EdgeBook, cfg: Config) -> dict[str, Any]:
    """Every leaf posterior, already shrunk through the three-level hierarchy."""
    n_b = int(cfg.edge_evidence_buckets)
    setups = [s.name.lower() for s in SetupFamily]
    mu, scale, dof, n_eff, lcb, ucb, out_var, var_mu = [], [], [], [], [], [], [], []
    names: list[str] = []
    q = float(cfg.edge_lcb_quantile)

    for k in range(4):
        for s in range(len(setups)):
            for b in range(n_b):
                est = book.estimate(k, s, b)
                # The Student-t scale is sqrt(b_n / (a_n kappa_n)); EdgeEstimate
                # reports var_mean = scale^2 * dof/(dof-2), and a_n >= a0 = 3 by
                # construction so dof > 2 always and the inversion is exact.
                sc = math.sqrt(max(est.var_mean * (est.dof - 2.0) / est.dof, 0.0))
                mu.append(est.mean)
                scale.append(sc)
                dof.append(est.dof)
                n_eff.append(est.n_eff)
                lcb.append(est.lcb)
                ucb.append(est.ucb)
                out_var.append(est.outcome_var)
                var_mu.append(est.var_mean)
                names.append(f"{REGIME_NAMES[k]}/{setups[s]}/b{b}")

    # Round trip: Pine will rebuild the bound from (mu_n, scale, dof). If that
    # does not reproduce the Edge Book's own lcb here, the port cannot either.
    worst = 0.0
    for i in range(len(mu)):
        rebuilt = mu[i] + student_t_ppf(q, dof[i]) * scale[i]
        worst = max(worst, abs(rebuilt - lcb[i]))
    if worst > 1e-9:
        raise AssertionError(f"lower-bound round trip failed by {worst:.3e} sigma")

    return {
        "setups": setups,
        "setup_priority": ["sweep_reversal", "compression_break", "range_fade", "continuation"],
        "n_setups": len(setups),
        "n_buckets": n_b,
        "bucket_edges": [0.25, 0.6, 1.0, 1.6][: max(n_b - 1, 0)],
        "bucket_source": "abs(pooled log-odds L)",
        "lcb_quantile": _r(q),
        "prior": {
            "mu0": _r(cfg.edge_prior_mean_sigma),
            "kappa0": _r(cfg.edge_prior_strength),
            "pooling_strength": _r(cfg.edge_pooling_strength),
            "a0": _r(book.a0),
            "b0": _r(book.b0),
        },
        "halflife_bars": _r(cfg.edge_halflife_bars),
        "cell_index": "idx = (regime * n_setups + setup) * n_buckets + bucket",
        "n_cells": len(mu),
        "cell_names": names,
        "lcb_round_trip_max_abs_error": _r(worst),
        "cells": {
            "mu_n": _rv(mu),
            "scale": _rv(scale),
            "dof": _rv(dof),
            "n_eff": _rv(n_eff),
            "outcome_var": _rv(out_var),
            "var_mean": _rv(var_mu),
            "lcb": _rv(lcb),
            "ucb": _rv(ucb),
        },
    }


