"""Freeze a trained TI-A into constants that a non-learning port can evaluate.

TradingView's Pine Script cannot learn. It has no cross-session persistence, no
optimiser, no way to accumulate an Edge Book across a universe of instruments,
and no way to fit an isotonic map. Everything in ``docs/01-THEORY.md`` that
depends on *estimation* therefore has to happen here, in Python, once; the port
only *evaluates*.

That split is not a compromise forced by the platform. It is the same split the
architecture already has: ``Provenance.DEV`` parameters are fit once on the
development universe and then frozen (``config.py``), and ``Provenance.ONLINE``
quantities are causal recursions that a streaming port can reproduce exactly.
This module writes out the first group -- plus the two learned objects, the Edge
Book posteriors and the calibration map -- as a single JSON manifest.

What is exported, and why each item is here:

``engines.correlation`` / ``engines.precision``
    The causally-estimated engine correlation matrix ``C`` from
    :class:`tia.fusion.calop.CALOP`, ridge-regularised by ``fusion_shrink``, and
    its inverse. Pine consumes ``C^-1`` directly so it never has to invert a
    matrix for the *total* breadth; the reliability scaling
    ``M = D^(1/2) C^-1 D^(1/2)`` stays live because reliabilities change every
    bar. The un-inverted ``C`` is also exported because the *aligned* breadth of
    :meth:`CALOP.fuse` needs a principal sub-matrix inverted at runtime.

``fusion.temperature`` / ``bias`` / ``evidence_sd``
    The three ``DEV`` parameters of §6.3. Frozen by definition.

``calibration.knots_x`` / ``knots_y``
    :meth:`IsotonicCalibrator.knots` -- the piecewise-linear monotone map fitted
    by PAVA on resolved outcomes. Pine interpolates it with the same linear rule
    ``numpy.interp`` uses.

``regime.tempering_exponent``
    ``eta = EBE_f / J`` of §5.3. Python re-estimates this every bar from a
    rolling 8x8 feature correlation; Pine takes the frozen value, because an
    8x8 correlation plus inverse per bar is not worth its cost for a quantity
    that moves this slowly. The realised dispersion of ``eta`` over the training
    run is exported alongside it so the approximation error is auditable.

``edge_book.cells``
    For every one of the ``4 x 4 x n_buckets`` leaves, the *hierarchically
    shrunk* Normal-Inverse-Gamma posterior: ``mu_n``, the Student-t ``scale``,
    ``dof`` and the effective count ``n_eff``. Pine reconstructs
    ``LCB_q = mu_n + t_{q,dof} * scale`` with the same Cornish-Fisher expansion
    :func:`tia.engines.edgebook.student_t_ppf` uses, so the two ports agree to
    the accuracy of that expansion and not to the accuracy of a table lookup.

Round-tripping is checked: :func:`export_frozen_model` recomputes every exported
lower credible bound from the exported triple and asserts agreement with the
Edge Book's own number.

The companion function :func:`emit_pine_constants` transpiles the manifest into
the ``BEGIN/END FROZEN MODEL`` region of the ``.pine`` files. Pine cannot read
files or parse JSON at runtime, so vectors and matrices become comma-separated
string literals that the script splits once on its first bar.
"""

