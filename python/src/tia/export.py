def train_reference_system(
    n_instruments: int = 6,
    n_bars: int = 9000,
    seed0: int = 1,
    cfg: Config | None = None,
) -> tuple[Any, dict[str, Any], dict[str, Any], tuple[float, float, int], np.ndarray]:
    """Train one Edge Book and one calibrator across a synthetic universe.

    This is the smallest honest instantiation of ``docs/01-THEORY.md`` §12:
    selectivity is applied per instrument, statistical power comes from pooling
    across instruments. A single series produces far too few trades for any of
    the exported posteriors to mean anything, and the exporter should not
    pretend otherwise -- so the default is a universe, not a symbol.

    The instruments are :func:`tia.synthetic.generate_with_regimes`, which is a
    *recovery* fixture, not a market. The numbers this produces are real in the
    sense that they came from the real training code; they are not real in the
    sense of describing any traded instrument. Re-run against the development
    universe before trading anything.
    """
    from .features.rolling import RollingCorrelation
    from .labeling.triple_barrier import apply_triple_barrier_to_bars
    from .labeling.weights import combined_weights
    from .pipeline import TIA
    from .synthetic import generate_with_regimes
    from .training import collect_candidates

    cfg = cfg or Config()
    book = EdgeBook(cfg)
    all_p: list[float] = []
    all_y: list[float] = []
    all_w: list[float] = []
    per_symbol: list[dict[str, Any]] = []
    longest: list[Any] = []

    for k in range(n_instruments):
        bars, _truth = generate_with_regimes(n=n_bars, seed=seed0 + k)
        if len(bars) > len(longest):
            longest = bars
        cands = collect_candidates(bars, cfg)
        arr = cands.arrays()
        if len(cands) == 0:
            per_symbol.append({"seed": seed0 + k, "n_bars": len(bars), "n_candidates": 0})
            continue
        res = apply_triple_barrier_to_bars(
            bars,
            entry_indices=arr["index"],
            directions=arr["direction"],
            stop_sigma=arr["stop_sigma"],
            target_sigma=arr["target_sigma"],
            sigma=arr["sigma"],
            max_holding=arr["max_holding"],
            execution_lag=cfg.execution_lag_bars,
        )
        w = combined_weights(
            n_bars=len(bars),
            entry_indices=res.entry_index,
            exit_indices=res.exit_index,
            halflife_bars=cfg.edge_halflife_bars,
        )
        ok = np.isfinite(res.ret_sigma)
        for j in np.nonzero(ok)[0]:
            book.observe(
                int(arr["regime"][j]),
                int(arr["setup"][j]),
                int(arr["bucket"][j]),
                float(res.ret_sigma[j]),
                weight=float(w[j]),
            )
        all_p.extend(arr["p_success"][ok].tolist())
        all_y.extend((res.outcome[ok] > 0).astype(float).tolist())
        all_w.extend(w[ok].tolist())
        per_symbol.append(
            {
                "seed": seed0 + k,
                "n_bars": len(bars),
                "n_candidates": int(len(cands)),
                "eligibility_rate": _r(cands.eligibility_rate),
                "hit_rate": _r(float((res.outcome[ok] > 0).mean())) if ok.any() else None,
                "mean_ret_sigma": _r(float(np.average(res.ret_sigma[ok], weights=w[ok]))) if ok.any() else None,
            }
        )

    cal = IsotonicCalibrator()
    if len(all_p) >= cfg.calibration_min_samples:
        cal.fit(np.array(all_p), np.array(all_y), weights=np.array(all_w))

    # Replay one instrument so the engine correlation estimator and the regime
    # tempering exponent hold measured values rather than their cold-start
    # priors. `learn=False` keeps the replay from adding to the pooled book.
    system = TIA(cfg, edge_book=book, learn=False)
    system.calibrator._iso = cal
    system.calibrator.active = cal.n_fit > 0
    # CALOP.observe() only feeds its estimator on bars where every engine in the
    # system is valid, and `crossasset`/`positioning` never are without
    # exogenous data -- so the system's own matrix would stay at its cold-start
    # prior forever. Estimate the ported engines' correlation directly, with the
    # same exponentially-weighted recursion CALOP uses.
    corr = RollingCorrelation(len(PINE_ENGINE_ORDER), halflife=float(cfg.correlation_window) / 2.0)
    tempers: list[float] = []
    for bar in longest:
        dec = system.on_bar(bar)
        t = float(system.regime_engine.state.temper)
        if math.isfinite(t) and system.kernel.snapshot.valid:
            tempers.append(t)
        outs = dec.engine_outputs
        vals = [outs[n].score if (n in outs and outs[n].valid) else math.nan for n in PINE_ENGINE_ORDER]
        if all(v == v for v in vals):
            corr.update(np.array(vals))

    t_arr = np.array(tempers) if tempers else np.array([1.0])
    tempering = (float(np.median(t_arr)), float(np.std(t_arr)), int(t_arr.size))
    if corr.count > 60:
        c_eng = corr.correlation(ridge=cfg.fusion_shrink)
        corr_source = (
            f"exponentially-weighted rolling correlation of the {len(PINE_ENGINE_ORDER)} "
            f"ported engine scores over {corr.count} bars, ridge {cfg.fusion_shrink}"
        )
    else:  # pragma: no cover - only on a pathologically short replay
        c_eng = np.full((len(PINE_ENGINE_ORDER),) * 2, 0.35)
        np.fill_diagonal(c_eng, 1.0)
        c_eng = (1.0 - cfg.fusion_shrink) * c_eng + cfg.fusion_shrink * np.eye(len(PINE_ENGINE_ORDER))
        corr_source = "CALOP cold-start prior (0.35 everywhere): replay too short to measure"

    dev_universe = {
        "kind": "synthetic",
        "generator": "tia.synthetic.generate_with_regimes",
        "n_instruments": n_instruments,
        "bars_per_instrument": n_bars,
        "seeds": [seed0 + k for k in range(n_instruments)],
        "warning": (
            "Synthetic recovery fixture, not a market. Re-run against the "
            "development universe of docs/00-PREREGISTRATION.md before trading."
        ),
        "per_symbol": per_symbol,
    }
    training = {
        "n_outcomes": len(all_p),
        "hit_rate": _r(float(np.mean(all_y))) if all_y else None,
        "isotonic_fitted": bool(cal.n_fit > 0),
        "isotonic_n_fit": int(cal.n_fit),
        "correlation_samples": _r(float(system.calop.diagnostics()["samples"])),
        "engine_mean_abs_corr": _r(float(system.calop.diagnostics()["mean_abs_corr"])),
        "replay_bars": len(longest),
    }
    return system, dev_universe, training, tempering


def main(argv: Sequence[str] | None = None) -> int:  # pragma: no cover - CLI
    import argparse

    ap = argparse.ArgumentParser(description="Freeze a trained TI-A for the Pine port.")
    # Repo-relative, not cwd-relative: running `python -m tia.export` from
    # python/ previously wrote a stray python/pine/ tree.
    _repo = pathlib.Path(__file__).resolve().parents[3]
    ap.add_argument("--out", default=str(_repo / "pine" / "frozen_model.json"))
    # Emitting is the DEFAULT, not an opt-in. A JSON manifest that has been
    # regenerated while the .pine files still carry the previous constants is
    # the worst of both worlds: the audit passes on the JSON, the chart runs the
    # old model, and nothing anywhere says so. This exact divergence shipped
    # once -- the Pine files kept a pre-fix isotonic map asserting 0% and 100%
    # confidence for a full commit. Use --no-emit to suppress deliberately.
    _pine = sorted((_repo / "pine").glob("*.pine"))
    ap.add_argument(
        "--emit", nargs="*", default=[str(x) for x in _pine],
        help=".pine files whose frozen region to rewrite (default: all of pine/*.pine)",
    )
    ap.add_argument("--no-emit", action="store_true", help="write the JSON only")
    ap.add_argument("--instruments", type=int, default=6)
    ap.add_argument("--bars", type=int, default=9000)
    ap.add_argument("--seed", type=int, default=1)
    ns = ap.parse_args(argv)

    system, dev, train, temper = train_reference_system(ns.instruments, ns.bars, ns.seed)
    model = export_frozen_model(
        system, ns.out, dev_universe=dev, training=train, tempering=temper
    )
    emitted: list[pathlib.Path] = []
    if ns.emit and not ns.no_emit:
        emitted = emit_pine_constants(model, *ns.emit)
    if emitted:
        print("emitted constants into " + ", ".join(p.name for p in emitted))
    elif not ns.no_emit:
        print("WARNING: no .pine files found to emit into", file=sys.stderr)
    print(
        f"wrote {ns.out}  schema={model['schema_version']}  "
        f"manifest={model['config_manifest_hash']}  "
        f"cells={model['edge_book']['n_cells']}  "
        f"outcomes={model['fusion']['n_outcomes']}  "
        f"isotonic={'on' if model['fusion']['isotonic_enabled'] else 'off'}"
    )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
